import assert from 'node:assert/strict';
import fs from 'node:fs';
import {getChapters} from '../notebook-templates.mjs';
import {AMP_C_NOTE,AMP_C_QUIZ,parseAmpcNote,validateAmpcQuiz,rankAmpcQuestions,renderAmpcStudy} from '../ampc-study.mjs';
const raw=fs.readFileSync(AMP_C_NOTE,'utf8');
const chapters=parseAmpcNote(raw);
assert.equal(chapters.length,8);
assert.deepEqual(chapters.map(x=>x.title),getChapters('cross').map(x=>x.title));
for(const x of ['ECKH','Hafnia alvei','CTRX','CFPM','MEPM','CMZ','ESBL','2026-07-30','2026-08-15'])
 assert.ok(raw.includes(x),'Missing reference: '+x);
const q=JSON.parse(fs.readFileSync(AMP_C_QUIZ,'utf8'));
assert.ok(validateAmpcQuiz(q));
assert.equal(q.length,10);
assert.equal(new Set(q.map(x=>x.id)).size,10);
assert.ok(q.every(x=>x.status==='draft'));
assert.ok(q.every(x=>x.reference_url==='https://www.idsociety.org/practice-guideline/amr-guidance/'));
const regular=JSON.parse(fs.readFileSync('content/review/bank-v2.json','utf8'));
assert.equal(regular.length,50,'Original 50 review questions retained');
const ordered=rankAmpcQuestions(q,{[q[5].id]:{rating:'again'}});
assert.equal(ordered[0],q[5].id);
const read=renderAmpcStudy({mode:'study',chapters,questions:q,tab:'notes'});
assert.equal((read.match(/class="ampc-chapter"/g)||[]).length,8);
assert.ok(read.includes('https://www.idsociety.org/practice-guideline/amr-guidance/'));
const questions=renderAmpcStudy({mode:'study',chapters,questions:q,tab:'quiz'});
assert.equal((questions.match(/name="ampcChoice"/g)||[]).length,4);
assert.ok(!questions.includes('正答：'));
const answers=renderAmpcStudy({mode:'study',chapters,questions:q,tab:'quiz',revealed:true,choice:q[0].correct_index});
assert.ok(answers.includes('練習上は正解'));
assert.equal((answers.match(/data-ampc-rating=/g)||[]).length,4);
const clinical=renderAmpcStudy({mode:'clinical',chapters,questions:q});
assert.ok(clinical.includes('臨床モードでは学習草案を表示しません'));
assert.ok(!clinical.includes('ampc-chapter'));
assert.ok(!clinical.includes('CFPM'));
assert.throws(()=>parseAmpcNote(raw.replace('## 3. 検査と評価','## 3. 検査')),/Incorrect AmpC chapter/);
assert.throws(()=>validateAmpcQuiz([...q,q[0]]),/requires 10/);
assert.throws(()=>validateAmpcQuiz(q.map((x,i)=>i===0?{...x,status:'verified'}:x)),/Invalid AmpC question/);
const app=fs.readFileSync('app.js','utf8');
assert.ok(app.includes("state.view==='ampc'"));
assert.ok(app.includes('astPocketAmpcStudyV1'));
assert.ok(app.includes('id="ampcQuizOpen"'));
assert.ok(app.includes("if(state.mode!=='study')return;"));
console.log('AmpC education tests passed: 8 chapters, 10 practice questions, 50 old questions preserved, clinical isolation.');
