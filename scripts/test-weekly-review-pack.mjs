import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createWeeklyReviewPack,parseImportantPoints,renderWeeklyReviewPack} from './build-weekly-review-pack.mjs';
const index=JSON.parse(fs.readFileSync('content/index.json','utf8'));
const taxonomy=JSON.parse(fs.readFileSync('data/topic-rules.json','utf8'));
const notePath='content/notes/mssa-bacteremia.md';
const note=fs.readFileSync(notePath,'utf8');
const weeklyPath='content/weekly/2026-10-09.md';
const weekly=fs.readFileSync(weeklyPath,'utf8');
const options={date:'2026-10-09',pointNumber:1,topicId:'infection-mssa-bacteremia',
 chapterId:'diagnosis',index,topics:taxonomy.topics,
 readWeekly:p=>fs.readFileSync(p,'utf8'),readNote:p=>fs.readFileSync(p,'utf8')};
const result=createWeeklyReviewPack(options);
assert.equal(result.status,'human_review_required');
assert.equal(result.medically_verified,false);
assert.equal(result.public_safety_re_reviewed,false);
assert.equal(result.auto_publish,false);
assert.equal(result.destination.note_path,notePath);
assert.equal(result.destination.chapter_id,'diagnosis');
assert.equal(result.provenance.original_point_exact,'S. aureus菌血症 → 再血培');
assert.match(result.provenance.weekly_sha256,/^[a-f0-9]{64}$/);
assert.match(result.destination.existing_note_sha256,/^[a-f0-9]{64}$/);
assert.equal(result.comparison.classification,'undetermined_human_review_required');
assert.equal(result.comparison.copy_to_notebook,false);
assert.equal(result.evidence.guideline_source_assigned,false);
assert.ok(result.comparison.similar_note_lines.length>=1);
assert.equal(parseImportantPoints(weekly).length,3);
const md=renderWeeklyReviewPack(result);
assert.ok(md.includes('S. aureus菌血症 → 再血培'));
assert.ok(md.includes('人による確認待ち'));
assert.ok(md.includes('医学的内容未承認'));
assert.ok(md.includes('2026-10-09.md'));
assert.ok(!md.includes('status: verified'));
assert.ok(!md.includes('公開しました'));
assert.deepEqual(createWeeklyReviewPack(options),result,'Deterministic output expected');
const wrong=(overrides)=>createWeeklyReviewPack({...options,...overrides});
assert.throws(()=>wrong({date:'2026-02-30'}),/invalid JST date/);
assert.throws(()=>wrong({date:'2026-10-16'}),/not published/);
assert.throws(()=>wrong({pointNumber:8}),/outside actual/);
assert.throws(()=>wrong({chapterId:'not_a_chapter'}),/unknown/);
assert.throws(()=>wrong({topicId:'invented'}),/not found/);
assert.throws(()=>wrong({index:{...index,notes:[]}}),/not public/);
assert.throws(()=>wrong({readNote:()=>note.replace('status: draft','status: verified')}),/only public draft notes/);
const contaminated=weekly.replace('S. aureus菌血症 → 再血培','患者ID: 1234 の菌血症');
assert.throws(()=>wrong({readWeekly:()=>contaminated}),/unsafe or invalid/);
const expanded=weekly.replace('S. aureus菌血症 → 再血培','S. aureus菌血症 → 追加で感染源も検討');
const expandedPack=wrong({readWeekly:()=>expanded});
assert.notEqual(expandedPack.provenance.weekly_sha256,result.provenance.weekly_sha256);
assert.equal(fs.readFileSync(notePath,'utf8'),note,'No notebook change');
assert.equal(fs.readFileSync(weeklyPath,'utf8'),weekly,'No Weekly change');
const cli=fs.readFileSync('scripts/build-weekly-review-pack.mjs','utf8');
assert.ok(cli.includes("flag:'wx'"),'Never overwrite prior outputs');
assert.ok(cli.includes('local-intake'));
assert.ok(!cli.includes('api.openai.com'));
const publicPilot='docs/review-drafts/weekly-2026-10-09-mssa-revision-proposal.md';
const pilot=fs.readFileSync(publicPilot,'utf8');
assert.ok(pilot.includes(result.provenance.original_point_exact),'Pilot must use real Weekly text');
assert.ok(pilot.includes('human_review_required'),'Pilot cannot imply medical approval');
assert.ok(pilot.includes('医学的な妥当性は未承認'),'Must disclose incomplete clinical review');
assert.ok(!index.notes.includes(publicPilot));
assert.ok(!index.weekly.includes(publicPilot));
assert.ok(pilot.includes('content/weekly/2026-10-09.md'));
console.log('Public dated Weekly -> review packet passed: genuine source point, note SHA, clinical safety holds, no API or publication.');
